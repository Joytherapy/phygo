-- Minimal replica of the production tables touched by the clinical-knowledge
-- migrations, with the same column types, defaults, keys and policies as on
-- 12 October 2026 (information_schema / pg_indexes / pg_policies). Only used
-- by run.sh on a throwaway local database.
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
end $$;

create table knowledge_base (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  condition_name text, condition_keywords text, goals text, progression_criteria text,
  return_to_activity_criteria text, outcome_measures text, clinical_tests text, red_flags text,
  typical_exercises text, contraindications text, source text, source_date text,
  translations jsonb default '{}'::jsonb, evidence_level text default 'high'::text,
  pathophysiology text, etiology_risk_factors text, differential_diagnosis text,
  related_condition_ids bigint[], icd10_code text, icd10_verified boolean not null default false
);
alter table knowledge_base enable row level security;
create policy "Enable read access for all users" on knowledge_base for select using (true);

create table rehab_phases (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  phase_number bigint, phase_name text, phase_criteria_to_start text, typical_duration text,
  phase_goals text, phase_exercises text, criteria_to_progress text,
  condition_id bigint,               -- no foreign key, as in production
  translations jsonb default '{}'::jsonb
);
alter table rehab_phases enable row level security;
create policy "Enable read access for all users" on rehab_phases for select using (true);

create table condition_translations (
  id bigserial primary key,
  condition_id integer not null references knowledge_base (id) on delete cascade,
  lang text not null, condition_name text, goals text, clinical_tests text, red_flags text,
  contraindications text, typical_exercises text, progression_criteria text,
  return_to_activity_criteria text, outcome_measures text, source_hash text not null,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique (condition_id, lang)
);

create table exercises (
  id uuid primary key default gen_random_uuid(),
  source text, external_id text, archived_at timestamptz
);
