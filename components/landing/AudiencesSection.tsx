import { ArrowRight, Check, GraduationCap, Smartphone, Stethoscope } from "lucide-react";
import type { AppLang } from "@/lib/i18n/uiStrings";
import { myPhygoLoginHref, signupHref, type LandingDict } from "@/lib/i18n/landingStrings";
import { Reveal, SectionHeader } from "./ui";

// Three experiences, verified in the code:
// - Students: profiles.practice_stage = 'student' (chosen in /onboarding).
//   middleware.ts sends students away from /dashboard, /dashboard/patients*
//   and /dashboard/agenda*; libraries, 3D maps, exercise library, quizzes and
//   the workspace stay available. They can switch to professional mode from
//   their profile.
// - Physiotherapists: same sign-up (/login?mode=signup), "Physiotherapist" in
//   onboarding.
// - Patients: invitation only (/my-phygo/join/[code], generated by the
//   physiotherapist); returning patients sign in at /my-phygo/login.
const ICONS = [GraduationCap, Stethoscope, Smartphone];

export default function AudiencesSection({
  lang,
  audiences,
  videoCalls,
}: {
  lang: AppLang;
  audiences: LandingDict["audiences"];
  videoCalls: boolean;
}) {
  const hrefs = [signupHref(lang), signupHref(lang), myPhygoLoginHref(lang)];

  return (
    <section id="audiences" aria-labelledby="audiences-title" className="relative scroll-mt-16 py-24 sm:py-32">
      <div className="mx-auto max-w-7xl px-4 sm:px-6">
        <SectionHeader id="audiences-title" index="01" eyebrow={audiences.eyebrow} title={audiences.title} intro={audiences.intro} />

        <Reveal className="relative mt-14">
          {/* The spine: one platform, three ways in */}
          <div aria-hidden className="relative mb-6 hidden items-center lg:flex">
            <span className="h-px flex-1 bg-gradient-to-r from-transparent via-ink/15 to-ink/15 dark:via-white/15 dark:to-white/15" />
            <span className="mx-4 rounded-full border border-black/[0.08] bg-white px-4 py-1.5 font-mono text-[10.5px] uppercase tracking-[0.14em] text-ink/60 dark:border-white/10 dark:bg-ink-soft dark:text-white/55">
              {audiences.spine}
            </span>
            <span className="h-px flex-1 bg-gradient-to-l from-transparent via-ink/15 to-ink/15 dark:via-white/15 dark:to-white/15" />
          </div>

          <div className="lp-ticks grid overflow-hidden rounded-[28px] border border-black/[0.08] bg-white shadow-soft dark:border-white/[0.09] dark:bg-[#111318] lg:grid-cols-[1fr_1.15fr_1fr]">
            {audiences.paths.map((path, i) => {
              const Icon = ICONS[i];
              const featured = i === 1;
              const items = videoCalls && path.videoItem ? [...path.items, path.videoItem] : path.items;
              return (
                <article
                  key={path.label}
                  aria-labelledby={`audience-${i}`}
                  className={`relative flex flex-col p-7 sm:p-9 ${
                    i > 0 ? "border-t border-black/[0.08] dark:border-white/[0.09] lg:border-l lg:border-t-0" : ""
                  } ${featured ? "bg-gradient-to-b from-electric/[0.06] to-emerald/[0.04] dark:from-electric/[0.10] dark:to-emerald/[0.05]" : ""}`}
                >
                  <div className="flex items-center justify-between">
                    <span
                      className={`inline-flex h-11 w-11 items-center justify-center rounded-2xl ${
                        featured ? "bg-gradient-to-br from-electric to-emerald text-white" : "bg-ink/[0.05] text-ink dark:bg-white/[0.07] dark:text-white"
                      }`}
                    >
                      <Icon size={20} aria-hidden />
                    </span>
                    <span className="font-mono text-[11px] text-ink/60 dark:text-white/55">{String.fromCharCode(65 + i)}</span>
                  </div>
                  <p className="mt-6 eyebrow text-electric-dark dark:text-electric-light">{path.label}</p>
                  <h3 id={`audience-${i}`} className="mt-3 font-display text-[1.45rem] font-semibold leading-[1.15] tracking-[-0.025em] text-ink dark:text-white text-balance">
                    {path.title}
                  </h3>
                  <p className="mt-3 text-[14.5px] leading-relaxed text-ink/65 dark:text-white/60">{path.text}</p>

                  <ul className="mt-6 space-y-2.5">
                    {items.map((item) => (
                      <li key={item} className="flex items-start gap-2.5 text-[14px] leading-snug text-ink/80 dark:text-white/75">
                        <Check size={15} aria-hidden className="mt-0.5 shrink-0 text-emerald-700 dark:text-emerald-light" />
                        {item}
                      </li>
                    ))}
                  </ul>

                  {path.note && (
                    <p className="mt-6 rounded-xl bg-ink/[0.035] px-4 py-3 text-[12.5px] leading-relaxed text-ink/70 dark:bg-white/[0.04] dark:text-white/65">
                      {path.note}
                    </p>
                  )}

                  <div className="mt-auto pt-8">
                    <a
                      href={hrefs[i]}
                      className={`group inline-flex w-full items-center justify-center gap-2 rounded-full px-5 py-3 text-[13.5px] font-semibold transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-electric focus-visible:ring-offset-2 ${
                        featured
                          ? "bg-ink text-white hover:bg-ink/90 dark:bg-white dark:text-ink dark:hover:bg-white/90"
                          : "border border-black/10 text-ink hover:border-ink/30 dark:border-white/15 dark:text-white dark:hover:border-white/35"
                      }`}
                    >
                      {path.cta}
                      <ArrowRight size={15} aria-hidden className="transition-transform group-hover:translate-x-0.5" />
                    </a>
                    {path.hint && <p className="mt-2.5 text-center text-[11.5px] text-ink/60 dark:text-white/55">{path.hint}</p>}
                  </div>
                </article>
              );
            })}
          </div>
        </Reveal>
      </div>
    </section>
  );
}
